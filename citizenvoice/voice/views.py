class QuestionViewSet(viewsets.ModelViewSet, UpdateModelMixin):
    """
    Question ViewSet used to query data from database.
    The `create` method is overwritten to accept one data object or an array of objects.
    """

    permission_classes = [IsAuthenticatedAndSelfOrMakeReadOnly]
    queryset = Question.objects.all()
    serializer_class = QuestionSerializer

    def create(self, request, *args, **kwargs):
        """
        Here we are overwriting the default create method from the Django REST framework to update or create Questions by list or by single instances
        """
        # Checks if the request data is a list, and if not it wraps it in a list
        data = request.data if isinstance(request.data, list) else [request.data]
        questions = []
        """
        Here we iterate over each item in the list and checks if it has an 'id' field. If it does, 
        it retrieves the existing Question object with that ID (if it exists). 
        If it doesn't have an 'id' field, it creates a new Question object.
        """

        for question_data in data:
            if "id" in question_data:
                question = Question.objects.filter(pk=question_data["id"]).first()
                if question is None:
                    continue
                serializer = self.get_serializer(
                    question,
                    data=question_data,
                    partial=True,
                    context={"request": request},
                )
            else:
                serializer = self.get_serializer(
                    data=question_data, context={"request": request}
                )
            serializer.is_valid(raise_exception=True)
            question = serializer.save()
            questions.append(question)

        update_fields = [
            "text",
            "explanation",
            "order",
            "required",
            "question_type",
            "choices",
            "survey",
            "is_geospatial",
            "has_text_input",
            "mapview",
            "topics",
        ]

        serializer = self.get_serializer(questions, many=True)
        headers = self.get_success_headers(serializer.data)
        return rf_response(
            serializer.data, status=status.HTTP_201_CREATED, headers=headers
        )

    def perform_create(self, serializer):
        update_fields = [
            "text",
            "explanation",
            "order",
            "required",
            "question_type",
            "choices",
            "survey",
            "is_geospatial",
            "has_text_input",
            "map_view",
        ]
        serializer.save(update_fields=update_fields)

    def perform_update(self, serializer):
        serializer.save(
            update_fields=[
                "text",
                "explanation",
                "order",
                "required",
                "question_type",
                "choices",
                "survey",
                "is_geospatial",
                "show_text",
                "map_view",
            ],
            update_conflicts={
                "text": "keep",
                "explanation": "keep",
                "order": "keep",
                "required": "keep",
                "question_type": "keep",
                "choices": "keep",
                "survey": "keep",
                "is_geospatial": "keep",
                "has_text_input": "keep",
                "map_view": "keep",
            },
        )

    @extend_schema(
        summary="Get ordered questions for survey",
        description="Retrieve all questions belonging to a specific survey, ordered by their sequence number (order field).",
        operation_id="getOrderedQuestions",
    )
    @action(detail=True, methods=["get"])
    def ordered_questions(self, request, pk=None):
        """
        Retrieve a list of questions for a given survey, ordered by the 'order' field.
        API url: `/api/questions/{survey_id}/ordered_questions`

        Parameters:
            request (Request): The request object used to make the API call.
            pk = survey_id (int): The primary key of the Survey instance to retrieve questions for.

        Returns:
            Response: A JSON response containing a list of serialized Question instances.
        """
        survey = get_object_or_404(Survey, pk=pk)
        questions = survey.question_set.all().order_by("order")
        serializer = self.get_serializer(questions, many=True)
        return rf_response(serializer.data)


class SurveyViewSet(viewsets.ModelViewSet):
    """
    Survey ViewSet used internally to query data from database.

    """

    permission_classes = [CanAccessSurvey]
    serializer_class = SurveySerializer

    def get_queryset(self):
        """
        Returns surveys based on user authentication:
        - Authenticated users: public surveys + their own surveys
        - Anonymous users: only public surveys
        - Private surveys (need_logged_user=True) only visible to designer
        """
        user = self.request.user
        now = timezone.now()
        
        # Base queryset: published and not expired
        base_queryset = Survey.objects.filter(
            is_published=True,
            expire_date__gte=now
        )
        
        if user.is_authenticated:
            # Authenticated users see:
            # 1. Public surveys (need_logged_user=False)
            # 2. Their own surveys (regardless of need_logged_user or publish status, but not expired)
            public_surveys = base_queryset.filter(need_logged_user=False)
            # Own surveys: include unpublished and private, but exclude expired
            own_surveys = Survey.objects.filter(
                designer=user,
                expire_date__gte=now
            )
            
            # Combine and remove duplicates
            queryset = (public_surveys | own_surveys).distinct().order_by("name")
        else:
            # Anonymous users only see public surveys
            queryset = base_queryset.filter(need_logged_user=False).order_by("name")
        
        return queryset

    def get_object(self):
        """
        Override to check permissions even if object is not in queryset.
        This ensures we return 403 (Forbidden) instead of 404 (Not Found)
        when user tries to access a survey they don't have permission to see.
        """
        # Get the object directly by pk, bypassing queryset filtering
        # This allows us to check permissions even if the object is filtered out
        lookup_url_kwarg = self.lookup_url_kwarg or self.lookup_field
        filter_kwargs = {self.lookup_field: self.kwargs[lookup_url_kwarg]}
        
        try:
            obj = Survey.objects.get(**filter_kwargs)
        except Survey.DoesNotExist:
            from rest_framework.exceptions import NotFound
            raise NotFound("Survey not found.")
        
        # Check object permissions (this will raise PermissionDenied if denied)
        self.check_object_permissions(self.request, obj)
        
        return obj

