    @extend_schema(
        summary="Create a new survey",
        description="Create a new survey with the specified name and description. The authenticated user becomes the survey designer.",
        operation_id="createNewSurvey",
    )
    @action(detail=False, methods=["POST"], url_path="create-survey", permission_classes=[IsAuthenticated])
    def create_survey(self, request, *args, **kwargs):
        """
        Create a new survey. Requires authentication.
        The authenticated user becomes the survey designer.
        """
        user = self.request.user
        
        survey_name = self.request.data.get("name")
        survey_description = self.request.data.get("description", "")
        
        if not survey_name:
            return rf_response(
                {"detail": "Survey name is required."},
                status=status.HTTP_400_BAD_REQUEST
            )
        
        once_up_a_time = datetime.now()
        tz_aware_datetime = timezone.make_aware(once_up_a_time)

        survey = Survey(
            name=survey_name,
            description=survey_description,
            publish_date=tz_aware_datetime,
            expire_date=tz_aware_datetime,
            designer=user,
        )
        survey.save()

        survey_serializer = SurveySerializer(
            survey, context={"request": request}
        )
        return rf_response(survey_serializer.data, status=status.HTTP_201_CREATED)

    @extend_schema(
        summary="Get survey questions",
        description="Retrieve questions for a published survey, ordered by sequence.",
        operation_id="getSurveyQuestions",
    )
    @action(detail=True, methods=["GET"], url_path="questions")
    def get_questions_of_survey(self, request, pk=None):
        """
        Get questions for a survey.
        Access rules:
        - Published public surveys: anyone can access
        - Published private surveys: only designer can access
        - Unpublished surveys: only designer can access
        """
        try:
            survey = Survey.objects.get(id=pk)
        except Survey.DoesNotExist:
            return rf_response(
                {"detail": "Survey not found."},
                status=status.HTTP_404_NOT_FOUND
            )
        
        user = self.request.user
        
        # Check access permissions
        # If survey is not published, only designer can access
        if not survey.is_published:
            if not user.is_authenticated or survey.designer != user:
                return rf_response(
                    {"detail": "You do not have permission to access this survey."},
                    status=status.HTTP_403_FORBIDDEN
                )
        
        # If survey is private (need_logged_user=True), only designer can access
        elif survey.need_logged_user:
            if not user.is_authenticated or survey.designer != user:
                return rf_response(
                    {"detail": "This survey requires authentication and ownership."},
                    status=status.HTTP_403_FORBIDDEN
                )
        
        # Survey is published and public, or user has access
        questions = Question.objects.filter(survey_id=pk).order_by("order")
        question_serializer = QuestionSerializer(
            questions, many=True, context={"request": request}
        )
        return rf_response(question_serializer.data)

    @extend_schema(
        summary="Generate shareable link",
        description="Generate or regenerate a shareable link for the survey. Only the survey designer can perform this action.",
        operation_id="generateShareableLink",
    )
    @action(detail=True, methods=["POST"], url_path="generate-shareable-link", permission_classes=[IsAuthenticated])
    def generate_shareable_link(self, request, pk=None):
        """
        Generate or regenerate a shareable link for the survey.
        Requires authentication and survey ownership.
        """
        try:
            survey = Survey.objects.get(id=pk)
        except Survey.DoesNotExist:
            return rf_response(
                {"detail": "Survey not found."},
                status=status.HTTP_404_NOT_FOUND
            )

        # Check ownership
        if survey.designer != request.user:
            return rf_response(
                {"detail": "You do not have permission to perform this action."},
                status=status.HTTP_403_FORBIDDEN
            )

        # Get request parameters
        requires_auth = request.data.get("requires_auth", False)
        expires_at_str = request.data.get("expires_at")
        
        expires_at = None
        if expires_at_str:
            try:
                # Parse ISO 8601 format datetime string
                expires_at = datetime.fromisoformat(expires_at_str.replace('Z', '+00:00'))
                if timezone.is_naive(expires_at):
                    expires_at = timezone.make_aware(expires_at)
            except (ValueError, TypeError, AttributeError):
                return rf_response(
                    {"detail": "Invalid expires_at format. Use ISO 8601 format (e.g., 2024-12-31T23:59:59Z)."},
                    status=status.HTTP_400_BAD_REQUEST
                )

        # Generate new token
        survey.shareable_token = survey.generate_shareable_token()
        survey.shareable_link_enabled = True
        survey.shareable_link_requires_auth = requires_auth
        survey.shareable_link_expires_at = expires_at
        survey.save()

        # Build shareable URL
        shareable_url = request.build_absolute_uri(f"/voice/v3/surveys/share/{survey.shareable_token}/")

        return rf_response({
            "shareable_token": survey.shareable_token,
            "shareable_url": shareable_url,
            "requires_auth": survey.shareable_link_requires_auth,
            "expires_at": survey.shareable_link_expires_at.isoformat() if survey.shareable_link_expires_at else None,
        }, status=status.HTTP_200_OK)

